# [목적] print()의 sep, end 옵션을 익힌다
# [설명] 기본은 공백 구분 + 줄바꿈입니다.

print("A", "B", "C")                 # 기본: 공백으로 구분
print("A", "B", "C", sep="-")        # 구분자 지정
print("A", "B", "C", sep="")         # 구분자 없음

print("줄바꿈", end=" ")             # 줄바꿈 대신 공백
print("없이 이어짐")

print("2026", "09", "02", sep="-")   # 날짜 형태로 조합
