# [목적] 7가지 산술 연산자의 결과를 한 번에 비교한다
# [설명] / 와 // 의 차이, % 의 쓰임에 특히 주목하세요.

a = 7
b = 2

print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)      # 나누기: 결과가 항상 실수(float)
print("a // b =", a // b)    # 몫: 소수점 버림
print("a % b =", a % b)      # 나머지
print("a ** b =", a ** b)    # 거듭제곱
