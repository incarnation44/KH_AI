# [목적] 이물 분류 번호를 입력받아 클래스 이름을 알려준다
# [설명] 라벨링 작업 중 번호가 헷갈릴 때 쓰는 간이 도구입니다.

class_map = {
    1: "나뭇잎류",
    2: "플라스틱·돌·금속 등",
    3: "나뭇가지류",
    4: "고무장갑(미사용)",
    5: "병해·갈변",
    6: "파·고추",
}

number = int(input("분류 번호(1~6)를 입력하세요: "))
name = class_map.get(number, "등록되지 않은 번호")

print(f"{number}번 => {name}")
