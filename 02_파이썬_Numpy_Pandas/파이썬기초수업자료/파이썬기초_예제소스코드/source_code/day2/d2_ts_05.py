# [목적] 좌표 쌍 여러 개를 튜플 리스트로 관리한다
# [설명] 값이 바뀌면 안 되는 데이터 묶음에 적합합니다.

keypoints = [
    ("코", 320, 180),
    ("왼쪽어깨", 280, 260),
    ("오른쪽어깨", 360, 260),
    ("왼쪽손목", 240, 400),
]

for name, x, y in keypoints:
    print(f"{name:<10} ({x:>4}, {y:>4})")

# 특정 관절 찾기
for name, x, y in keypoints:
    if name == "왼쪽손목":
        print(f"\n왼쪽손목 높이: y={y}")
        print("어깨보다 아래인가?", y > 260)
